/**
 * The OC mark, rasterised to ASCII.
 *
 * Generated from /logo/mark-1.svg by sampling it onto a 104-column canvas and
 * mapping luminance to the ramp ' ·:+*#@'. Row count preserves the mark's
 * 634:349 aspect after correcting for monospace advance (~0.5 of line-height).
 *
 * The two-tone split survives the conversion: the dense `@` ring is the closed
 * O, the sparse `:` field is the gold C. That is the whole reason this works as
 * a brand texture rather than generic noise.
 *
 * Text, not a raster — the reference template ships a 2800px PNG for the same
 * effect. This is ~2.3 KB, inherits currentColor, and stays crisp at any size.
 */
